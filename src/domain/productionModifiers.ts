import type { ProductionModifier, ResourceAmounts } from './productionCalculator'

const ALL_RESOURCES: ResourceAmounts = { food: 1, wood: 1, gold: 1, stone: 1 }

function gathering(
  id: string,
  label: string,
  description: string,
  resourceMultiplier: Partial<ResourceAmounts>,
  options: Pick<ProductionModifier, 'defaultSelected' | 'foodSources' | 'age'> = {},
): ProductionModifier {
  return { id, label, description, kind: 'gathering', resourceMultiplier, ...options }
}

function dropOff(
  id: string,
  label: string,
  description: string,
  dropOffPercent: Partial<ResourceAmounts>,
  options: Pick<ProductionModifier, 'defaultSelected' | 'age'> = {},
): ProductionModifier {
  return { id, label, description, kind: 'dropOff', dropOffPercent, ...options }
}

function speed(
  id: string,
  label: string,
  description: string,
  multiplier: number,
  target: ProductionModifier['target'],
  options: Pick<ProductionModifier, 'defaultSelected' | 'age'> = {},
): ProductionModifier {
  return { id, label, description, kind: 'speed', multiplier, target, ...options }
}

function cost(
  id: string,
  label: string,
  description: string,
  multiplier: number,
  target: ProductionModifier['target'],
  options: Pick<ProductionModifier, 'defaultSelected' | 'age'> = {},
): ProductionModifier {
  return { id, label, description, kind: 'cost', multiplier, target, ...options }
}

function passive(
  id: string,
  label: string,
  description: string,
  passivePerMinute: Partial<ResourceAmounts>,
): ProductionModifier {
  return { id, label, description, kind: 'passive', passivePerMinute }
}


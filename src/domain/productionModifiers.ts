/** Current calculator-style optional civ modifiers, kept as local data so the math stays testable. */
export function productionModifiersForCiv(civ: string): ProductionModifier[] {
  return (CIV_MODIFIERS[civ] ?? []).map((modifier) => ({
    ...modifier,
    resourceMultiplier: modifier.resourceMultiplier
      ? { ...ALL_RESOURCES, ...modifier.resourceMultiplier }
      : undefined,
    dropOffPercent: modifier.dropOffPercent ? { ...modifier.dropOffPercent } : undefined,
    passivePerMinute: modifier.passivePerMinute ? { ...modifier.passivePerMinute } : undefined,
  }))
}

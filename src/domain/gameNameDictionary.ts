/** Canonical English civ/map keys → localized display names. Used by `gameName()`. */

/** `Dry Arabia` → `dry_arabia`, `Nagari` → `nagari`. */
export function englishNameToSlug(english: string): string {
  return english
    .trim()
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_|_$/g, '')
}

/** Duplicate display-name entries under Relic-style slugs so both keys resolve. */
export function expandGameNameKeys(table: Record<string, string>): Record<string, string> {
  const out: Record<string, string> = { ...table }
  for (const [english, translated] of Object.entries(table)) {
    const slug = englishNameToSlug(english)
    if (slug && out[slug] == null) out[slug] = translated
  }
  return out
}

export function lookupCivOrMapName(
  table: Record<string, string>,
  input: string,
): string | undefined {
  if (!input) return undefined
  const trimmed = input.trim()
  const slug = englishNameToSlug(trimmed)
  return table[trimmed] ?? table[slug] ?? undefined
}

